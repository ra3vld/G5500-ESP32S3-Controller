#!/usr/bin/env python3
"""Generate the compact LVGL font sizes from DejaVu Sans (4 bpp)."""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
FULL=sorted(set(range(32,127))|set(range(0x400,0x460))|{0xb0,0xb7,0x2014,0x2212})
NUMBERS=sorted(set(map(ord,' 0123456789.-/NC°—−')))
def generate():
 out=['// Generated by tools/generate_panel_fonts.py. Font license: docs/licenses/DejaVu.txt.\n#include "build_config.hpp"\n#if GRAPHICAL_DISPLAY\n#include <lvgl.h>']
 for size in (14,18,40,56):
  font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',size)
  points=FULL if size<=18 else NUMBERS
  bitmap=[];metrics=['  {0,0,0,0,0,0},']; ascent,descent=font.getmetrics()
  for point in points:
   char=chr(point);l,t,r,b=font.getbbox(char,anchor='ls');w,h=r-l,b-t
   img=Image.new('L',(w,h));ImageDraw.Draw(img).text((-l,-t),char,font=font,fill=255,anchor='ls')
   pixels=[(p+8)//17 for p in img.getdata()];offset=len(bitmap)
   bitmap.extend((pixels[i]<<4)|(pixels[i+1] if i+1<len(pixels) else 0) for i in range(0,len(pixels),2))
   metrics.append(f'  {{{offset},{round(font.getlength(char)*16)},{w},{h},{l},{-b}}},')
  out += [f'namespace font{size} {{', 'static const uint8_t bitmap[] = {']
  out += ['  '+','.join(f'0x{b:02x}' for b in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24)]
  out += ['};','static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {',*metrics,'};','static const uint16_t unicode[] = {'+','.join(str(p-32) for p in points)+'};',f'''static const lv_font_fmt_txt_cmap_t maps[] = {{
  {{.range_start=32,.range_length={points[-1]-31},.glyph_id_start=1,.unicode_list=unicode,
    .glyph_id_ofs_list=nullptr,.list_length={len(points)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};
static const lv_font_fmt_txt_dsc_t descriptor = {{
  .glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=maps,.kern_dsc=nullptr,
  .kern_scale=0,.cmap_num=1,.bpp=4,.kern_classes=0,.bitmap_format=0
}};
}}
const lv_font_t panel_font_{size} = {{
  .dsc=&font{size}::descriptor,.fallback=nullptr,.user_data=nullptr,
  .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
  .line_height={ascent+descent},.base_line={descent},.subpx=LV_FONT_SUBPX_NONE,
  .underline_position=0,.underline_thickness=1
}};''']
 out.append('#endif\n');return '\n'.join(out)
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
 dest=ROOT/'G5500_Fork/panel_fonts.cpp';value=generate()
 if a.check:
  if not dest.exists() or dest.read_text()!=value:raise SystemExit('panel_fonts.cpp is stale')
 else:dest.write_text(value)
