#!/usr/bin/env python3
"""Losslessly pack the original RGB565 TFT image into palette + byte runs."""
import argparse
import hashlib
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'G5500_Fork/cat_image.h'
OUTPUT = ROOT / 'G5500_Fork/tft_image.hpp'


def generate():
    source = SOURCE.read_text()
    width = int(re.search(r'CAT_IMAGE_W\s*=\s*(\d+)', source)[1])
    height = int(re.search(r'CAT_IMAGE_H\s*=\s*(\d+)', source)[1])
    pixels = [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]+)', source)]
    if len(pixels) != width * height:
        raise ValueError('Original image dimensions do not match its pixels')
    palette = sorted(set(pixels))
    if len(palette) > 256:
        raise ValueError('Image needs more than 256 lossless colors')
    indices = {color: i for i, color in enumerate(palette)}
    raw = bytes(indices[color] for color in pixels)
    packed = bytearray()
    at = 0
    while at < len(raw):
        run = 1
        while at + run < len(raw) and raw[at + run] == raw[at] and run < 130:
            run += 1
        if run >= 3:
            packed.extend((128 | (run - 3), raw[at]))
            at += run
        else:
            start = at
            at += run
            while at < len(raw) and at - start < 128:
                if at + 2 < len(raw) and raw[at] == raw[at + 1] == raw[at + 2]:
                    break
                at += 1
            packed.append(at - start - 1)
            packed.extend(raw[start:at])
    original = struct.pack('<' + 'H' * len(pixels), *pixels)
    lines = ['// Generated by tools/generate_tft_image.py; GPL-3.0.',
             '// Original cat_image.h is preserved; RGB565 sha256=' + hashlib.sha256(original).hexdigest(),
             '#pragma once', '#include <cstdint>', '#include <cstddef>',
             '#ifdef ARDUINO', '#include <Arduino.h>', '#else',
             '#ifndef PROGMEM', '#define PROGMEM', '#endif', '#endif',
             'namespace forkrot {',
             f'inline constexpr unsigned CAT_IMAGE_W={width}, CAT_IMAGE_H={height};',
             'inline const uint16_t TFT_IMAGE_PALETTE[] PROGMEM = {']
    for offset in range(0, len(palette), 12):
        lines.append('  ' + ','.join(f'0x{n:04x}' for n in palette[offset:offset+12]) + ',')
    lines.extend(['};', 'inline const uint8_t TFT_IMAGE_PACKED[] PROGMEM = {'])
    for offset in range(0, len(packed), 20):
        lines.append('  ' + ','.join(f'0x{n:02x}' for n in packed[offset:offset+20]) + ',')
    lines.extend(['};', '}'])
    return '\n'.join(lines) + '\n', pixels, len(packed) + len(palette) * 2


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, pixels, size = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            parser.error('TFT asset is stale; run python3 tools/generate_tft_image.py')
    else:
        temporary = OUTPUT.with_suffix('.hpp.tmp')
        temporary.write_text(text)
        temporary.replace(OUTPUT)
    print(f'TFT image: {len(pixels)*2} -> {size} bytes, lossless RGB565')
