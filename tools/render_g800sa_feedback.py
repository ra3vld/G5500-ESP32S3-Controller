#!/usr/bin/env python3
"""Render the differential G-800SA position input as SVG, PNG and vector PDF."""
from pathlib import Path
from render_g800sa_speed import Drawing, INK, RED, BLUE, GREEN
from schematic_svg import render_svg

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/hardware/g800sa'
OUT.mkdir(parents=True, exist_ok=True)
d = Drawing('G-800SA → ESP32: дифференциальный вход положения',
            'Два сигнала A/B и отдельная земля G. Одна MCP6002, питание 3,3 В.', 1, total=1)
d.box(70,165,2860,130,'#fff4db','#dfbb6b')
d.t(95,207,'A → J1005/1 (P6/2). B → J1005/2 (P6/3). G → J1005/9 и GND ESP32.',31,b=True)
d.t(95,250,'B не соединять с GND. Проверить G по минусу C1008. Штатные провода датчика сохранить.',29)
d.t(95,285,'Разность A−B: 0…+5 В. Каждый вход A и B относительно G: 0…+15 В.',27)

# U1A: R2 || R7 = R4 = 150 kohm; output = .0625*VDD + .15*(A-B).
d.label(100,600,'A • вход +',RED);d.wire((100,600),(300,600))
d.rh(300,600,'R1','1 МОм, 1%');d.wire((450,600),(1080,600))
d.dot(620,600);d.wire((620,600),(620,700));d.rv(620,700,'R2','160 кОм, 1%',False);d.wire((620,840),(620,900))
d.t(440,765,'R2',25,b=True);d.t(370,810,'160 кОм, 1%',24)
d.dot(820,600);d.wire((820,600),(820,700));d.cap(820,700,'C1','10 нФ');d.wire((820,840),(820,900))
d.wire((620,900),(820,900));d.gnd(720,900,'G / GND_ESP')
d.label(600,400,'+3,3 В',RED);d.wire((600,400),(780,400));d.rh(780,400,'R7','2,4 МОм, 1%')
d.wire((930,400),(980,400),(980,600));d.dot(980,600)
d.wire((1080,510),(1080,890),(1400,700),(1080,510))
d.t(1095,615,'+',32);d.t(1095,815,'−',32);d.t(1030,580,'3',25);d.t(1030,780,'2',25);d.t(1405,680,'1',25)
d.t(1120,450,'U1A MCP6002',30,b=True);d.wire((1400,700),(1900,700));d.dot(1470,700)
d.label(100,1100,'B • вход −',BLUE);d.wire((100,1100),(300,1100));d.rh(300,1100,'R3','1 МОм, 1%')
d.wire((450,1100),(980,1100),(980,800),(1080,800));d.dot(980,1040);d.dot(980,930)
d.wire((980,1040),(1100,1040));d.rh(1100,1040,'R4','150 кОм, 1%');d.wire((1250,1040),(1470,1040),(1470,700));d.dot(1470,930)
# C5 is across feedback R4, not from the inverting input to ground.
d.wire((980,930),(1140,930));d.wire((1140,908),(1140,952));d.wire((1160,908),(1160,952))
d.wire((1160,930),(1470,930));d.t(1270,875,'C5',25,b=True);d.t(1270,915,'10 нФ',24)
d.t(1020,1195,'U1A ≈ 0,20625 + 0,15 × (A−B), В',28,b=True)
d.t(100,1280,'G • земля: J1005/9',30,b=True);d.terminal(100,1320);d.wire((100,1320),(630,1320));d.gnd(630,1320,'GND_ESP')
d.t(100,1415,'Сверить G с минусом C1008 при отключённом питании.',27)

# U1B is a noninverting amplifier, gain 1 + R6/R5 = 2.2.
d.wire((1900,610),(1900,990),(2220,800),(1900,610));d.t(1915,715,'+',32);d.t(1915,915,'−',32)
d.t(1850,680,'5',25);d.t(1850,880,'6',25);d.t(2225,780,'7',25);d.t(1940,550,'U1B MCP6002',30,b=True)
d.wire((2220,800),(2370,800));d.dot(2280,800);d.wire((1900,900),(1800,900),(1800,1210));d.dot(1800,1150)
d.wire((1800,1150),(1950,1150));d.rh(1950,1150,'R6','12 кОм, 1%');d.wire((2100,1150),(2280,1150),(2280,800))
d.rv(1800,1210,'R5','10 кОм, 1%');d.wire((1800,1350),(1800,1380));d.gnd(1800,1380,'G / GND_ESP')
d.rh(2370,800,'R9','1 кОм');d.wire((2520,800),(2850,800));d.label(2850,800,'AZ ADC',GREEN)
d.dot(2600,800);d.wire((2600,800),(2600,900));d.cap(2600,900,'','');d.t(2420,960,'C2',25,b=True);d.t(2420,1000,'100 нФ',24);d.wire((2600,1040),(2600,1100));d.gnd(2600,1100,'G')

def diode_up(x,y,name):
    d.wire((x,y),(x,y+35));d.wire((x-22,y+35),(x+22,y+35));d.wire((x-22,y+35),(x-22,y+25));d.wire((x+22,y+35),(x+22,y+45))
    d.wire((x,y+35),(x-22,y+75),(x+22,y+75),(x,y+35));d.wire((x,y+75),(x,y+110))
    d.t(x+35,y+42,name,25,b=True);d.t(x+35,y+78,'BAT85',23);d.t(x-47,y+28,'K',22);d.t(x-47,y+95,'A',22)

d.dot(2730,800);d.wire((2730,800),(2730,620));diode_up(2730,510,'D1');d.wire((2730,510),(2730,450));d.t(2660,420,'+3,3 В',27,RED,True)
d.wire((2730,800),(2730,900));diode_up(2730,900,'D2');d.wire((2730,1010),(2730,1100));d.gnd(2730,1100,'G')
d.box(2380,1240,550,170,'#edf5ff','#9bbbe0');d.t(2400,1285,'ADC подключать напрямую.',26,b=True)
d.t(2400,1330,'Второй делитель 6,8/4,7 кОм',25);d.t(2400,1375,'между R9 и ADC не ставить.',25)

d.box(70,1490,900,400);d.t(100,1540,'ПИТАНИЕ U1: 8 → +3,3 В; 4 → G',29,b=True)
d.wire((170,1610),(820,1610));d.t(100,1595,'+3,3 В',25,RED,True);d.wire((170,1800),(820,1800));d.gnd(820,1800,'G / GND_ESP')
d.box(120,1670,100,80,'white',INK);d.t(140,1720,'U1',25,b=True);d.wire((170,1610),(170,1670));d.wire((170,1750),(170,1800));d.t(135,1655,'8',22);d.t(135,1783,'4',22)
for x,name,value in [(330,'C3','100 нФ'),(520,'C4','1 мкФ')]:
    d.dot(x,1610);d.cap(x,1640,name,value);d.wire((x,1610),(x,1640));d.wire((x,1780),(x,1800));d.dot(x,1800)
d.dot(740,1610);d.wire((740,1610),(740,1640));d.rv(740,1640,'R8','510 Ом');d.wire((740,1780),(740,1800));d.dot(740,1800)

d.box(1000,1490,930,400);d.t(1030,1540,'ПЕРЕДАЧА ПРИ ПИТАНИИ 3,30 В',29,b=True)
d.t(1030,1600,'UADC ≈ 0,45375 + 0,33 × (A−B), В',29,b=True)
for y,label in [(1660,'A−B = 0 В → ADC ≈ 0,454 В'),(1710,'A−B = 1,2 В → ADC ≈ 0,850 В'),(1760,'A−B = 5 В → ADC ≈ 2,104 В')]:d.t(1030,y,label,28)
d.t(1030,1820,'Смещение сохраняет работу ОУ вдали от нуля.',25);d.t(1030,1860,'В прошивке: калибровка по нескольким точкам.',25)
d.box(1960,1490,970,400);d.t(1990,1540,'ДЕТАЛИ И ПОДКЛЮЧЕНИЕ',29,b=True)
for y,label in [(1595,'U1: MCP6002-I/SN, SOIC-8. R1–R7: 1%.'),(1645,'R1 = R3; R4 = R2∥R7 = 150 кОм.'),(1695,'Подбор отношений до 0,1% уменьшает'),(1735,'влияние общего напряжения A/B.'),(1785,'C1/C5: 10 нФ, одинаковые; C2/C3: 100 нФ.'),(1825,'C4: 1 мкФ. R8/R9: 1–5%, 0,25 Вт.'),(1865,'Керамика X7R ≥16 В; C3 у выводов U1.')]:d.t(1990,y,label,26)
d.footer('G — земля CNTL-UNIT, не провод B датчика. Не добавлять связь G с силовым минусом N ради скорости.')
base = OUT / 'g800sa-feedback-5v.svg'
base.write_text(d.finish());render_svg(base)
