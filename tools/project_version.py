#!/usr/bin/env python3
"""Derive SemVer from reachable release tags and Conventional Commits; never tag or commit."""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
RELEASE = re.compile(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)")
CONVENTIONAL = re.compile(r"([a-z]+)(?:\([^\n()]+\))?(!)?: .+")


def git(root, *args):
    return subprocess.check_output(['git', *args], cwd=root, text=True,
                                   stderr=subprocess.PIPE).strip()


def bump_level(message):
    subject = CONVENTIONAL.fullmatch(message.splitlines()[0])
    if (subject and subject[2]) or re.search(r'^BREAKING[ -]CHANGE: ', message, re.M):
        return 3
    if subject and subject[1] == 'feat':
        return 2
    # Existing free-form subjects, fixes and other changes start the next patch.
    return 1


def render(identity):
    return ('// Generated by tools/project_version.py; do not edit.\n#pragma once\n'
            'namespace forkrot::firmware {\n'
            f'inline constexpr char VERSION[] = {json.dumps(identity["version"])};\n'
            f'inline constexpr char COMMIT[] = {json.dumps(identity["commit"])};\n'
            f'inline constexpr bool DIRTY = {str(identity["dirty"]).lower()};\n'
            '}\n')


def resolve(root=ROOT):
    root = Path(root).resolve()
    source = (root / 'G5500_Fork/project_version.hpp').read_text()
    base = re.search(r'^#define PROJECT_BASE_VERSION "([^"]+)"$', source, re.M)[1]
    anchor = re.search(r'^#define PROJECT_BASE_COMMIT "([0-9a-f]{40})"$', source, re.M)[1]
    if not RELEASE.fullmatch(base):
        raise ValueError('PROJECT_BASE_VERSION must be MAJOR.MINOR.PATCH without leading zeroes')
    try:
        top = Path(git(root, 'rev-parse', '--show-toplevel')).resolve()
    except subprocess.CalledProcessError:
        top = None
    if top != root:
        # Source archives carry the exact identity captured when they were packaged.
        saved = root / 'G5500_Fork/build_identity.hpp'
        if saved.exists():
            text = saved.read_text()
            version = re.search(r'VERSION\[\] = ("[^"\n]+");', text)
            commit = re.search(r'COMMIT\[\] = ("[^"\n]+");', text)
            dirty = re.search(r'DIRTY = (true|false);', text)
            if not all((version, commit, dirty)):
                raise ValueError('Invalid archived build identity')
            return dict(version=json.loads(version[1]), commit=json.loads(commit[1]), dirty=dirty[1] == 'true')
        return dict(version=base + '+unknown', commit='unknown', dirty=False)

    commit = git(root, 'rev-parse', '--short=7', 'HEAD')
    dirty = bool(git(root, 'status', '--porcelain', '--untracked-files=normal'))
    candidates = []
    for tag in git(root, 'tag', '--merged', 'HEAD', '--list', 'v*').splitlines():
        match = RELEASE.fullmatch(tag[1:])
        if match:
            distance = int(git(root, 'rev-list', '--count', tag + '..HEAD'))
            candidates.append((distance, tuple(-int(n) for n in match.groups()), tag))
    if candidates:
        _, _, anchor = min(candidates)
        base = anchor[1:]
    else:
        # Do not invent a version from incomplete (e.g. shallow) history.
        try:
            git(root, 'merge-base', '--is-ancestor', anchor, 'HEAD')
        except subprocess.CalledProcessError as error:
            raise ValueError('Version baseline is unavailable; fetch full history and tags') from error
    messages = git(root, 'log', '--format=%B%x00', anchor + '..HEAD')
    messages = [message.strip() for message in messages.split('\0') if message.strip()]
    if messages:
        major, minor, patch = map(int, base.split('.'))
        level = max(map(bump_level, messages))
        if level == 3:
            major, minor, patch = major + 1, 0, 0
        elif level == 2:
            minor, patch = minor + 1, 0
        else:
            patch += 1
        base = f'{major}.{minor}.{patch}-dev.{len(messages)}'
    if messages or dirty:
        base += '+g' + commit + ('.dirty' if dirty else '')
    return dict(version=base, commit=commit, dirty=dirty)


def generate(root=ROOT, output=None):
    root = Path(root)
    output = Path(output) if output else root / 'G5500_Fork/build_identity.hpp'
    identity = resolve(root)
    content = render(identity)
    if not output.exists() or output.read_text() != content:
        output.parent.mkdir(parents=True, exist_ok=True)
        temporary = output.with_suffix('.hpp.tmp')
        temporary.write_text(content)
        temporary.replace(output)
    return identity


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='generated C++ identity header')
    args = parser.parse_args()
    try:
        print(json.dumps(generate(output=args.output)))
    except (ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f'Version calculation failed: {error}\n')


if __name__ == '__main__':
    main()
